let webhookSequence = 0;
async function webhook(
  values: Record<string, unknown> & { storeDomain: string; platform?: string },
): Promise<string> {
  const { storeDomain, platform, ...rest } = values;
  return (await seed('webhook_events', {
    platform: platform ?? 'shopify',
    job_type: 'order.create',
    idempotency_key: `delivery-${++webhookSequence}`,
    store_domain: storeDomain,
    raw_payload: orderPayload,
    status: 'completed',
    received_at: ago(72 * HOUR),
    ...rest,
  }))!;
}

