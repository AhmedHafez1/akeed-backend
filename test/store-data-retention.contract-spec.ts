/**
 * Every table from the application schema with its real constraints and FK
 * delete actions (generated by drizzle-kit from `schema.ts`). RLS policies,
 * views and the Supabase `auth` schema are left out: nothing here needs them.
 */
async function createSchema(): Promise<void> {
  const kit = require(
    resolve(__dirname, '../node_modules/drizzle-kit/api.js'),
  ) as {
    generateDrizzleJson: (imports: Record<string, unknown>) => unknown;
    generateMigration: (from: unknown, to: unknown) => Promise<string[]>;
  };
  const statements = await kit.generateMigration(
    kit.generateDrizzleJson({}),
    kit.generateDrizzleJson(tables as Record<string, unknown>),
  );
  await client.unsafe(
    `CREATE FUNCTION "${namespace}".uuid_generate_v4() RETURNS uuid LANGUAGE sql AS 'SELECT gen_random_uuid()'`,
  );
  for (const statement of statements) {
    if (
      /^\s*(CREATE POLICY|CREATE VIEW|CREATE SCHEMA)/.test(statement) ||
      /ENABLE ROW LEVEL SECURITY/.test(statement) ||
      /"auth"\./.test(statement)
    )
      continue;
    // `db:pull` left operator classes on some index definitions that do not
    // match their column types; the default class is right for every index.
    const ddl = /^\s*CREATE (UNIQUE )?INDEX/.test(statement)
      ? statement.replace(/\s+[a-z0-9_]+_ops\b/g, '')
      : statement;
    await client.unsafe(ddl.replaceAll('"public".', `"${namespace}".`));
  }
}

/**
 * Inserts a row, filling every NOT NULL column without a default that the
 * caller left out with a synthetic value of its type.
 */
const requiredColumns = new Map<
  string,
  Array<{ name: string; type: string; udt: string }>
>();
async function seed(
  table: string,
  values: Record<string, unknown>,
): Promise<string | undefined> {
  if (!requiredColumns.has(table)) {
    const rows = await client<
      Array<{ name: string; type: string; udt: string }>
    >`
      SELECT column_name AS name, data_type AS type, udt_name AS udt
      FROM information_schema.columns
      WHERE table_schema = ${namespace} AND table_name = ${table}
        AND is_nullable = 'NO' AND column_default IS NULL`;
    requiredColumns.set(table, [...rows]);
  }
  const row: Record<string, unknown> = { ...values };
  for (const column of requiredColumns.get(table)!) {
    if (column.name in row) continue;
    if (column.type === 'uuid') row[column.name] = randomUUID();
    else if (column.type === 'integer' || column.type === 'bigint')
      row[column.name] = 1;
    else if (column.type === 'numeric') row[column.name] = '0';
    else if (column.type === 'boolean') row[column.name] = false;
    else if (column.type.startsWith('timestamp'))
      row[column.name] = NOW.toISOString();
    else if (column.type === 'date') row[column.name] = '2026-11-01';
    else if (column.type === 'jsonb') row[column.name] = {};
    else if (column.type === 'ARRAY') row[column.name] = [];
    else if (column.type === 'USER-DEFINED') {
      const [label] = await client<Array<{ label: string }>>`
        SELECT e.enumlabel AS label FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = ${column.udt} ORDER BY e.enumsortorder LIMIT 1`;
      row[column.name] = label.label;
    } else row[column.name] = `synthetic-${column.name}-${randomUUID()}`;
  }
  const columns = Object.keys(row);
  const [inserted] = await client.unsafe<Array<{ id?: string }>>(
    `INSERT INTO "${namespace}"."${table}" (${columns.map((c) => `"${c}"`).join(', ')})
     VALUES (${columns.map((_, i) => `$${i + 1}`).join(', ')})
     RETURNING *`,
    columns.map((c) => {
      const value = row[c];
      return value !== null &&
        typeof value === 'object' &&
        !Array.isArray(value)
        ? JSON.stringify(value)
        : value;
    }) as never[],
  );
  return inserted?.id;
}

async function countWhere(table: string, where: string): Promise<number> {
  const [row] = await client.unsafe<Array<{ n: number }>>(
    `SELECT count(*)::int AS n FROM "${namespace}"."${table}" WHERE ${where}`,
  );
  return row.n;
}

